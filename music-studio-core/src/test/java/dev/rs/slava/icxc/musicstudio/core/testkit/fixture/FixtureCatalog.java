/**
 * Hand-written expected read results of the {@link Fixture}s, mirrored from {@code generate_fixtures.py}.
 * Never generated by running a reader of ours.
 *
 * <p>Stream info: 1 s of silence encoded by LAME is about 1.045 s long; readers must be within
 * {@link #DURATION_TOLERANCE}. Issues are compared by severity, code and field (messages are free text).
 */
public final class FixtureCatalog {

    /** Allowed difference between the expected and the read duration. */
    public static final Duration DURATION_TOLERANCE = Duration.ofMillis(100);
    /** Size of the 1×1 JPEG embedded in the picture fixtures. */
    public static final int COVER_JPEG_BYTES = 207;

    private static final StreamInfo STREAM = new StreamInfo(Duration.ofMillis(1045), 128, false);

    private FixtureCatalog() {
    }

    /**
     * @param fixture a fixture
     * @return the expected result, or empty if the fixture must fail with CORRUPT
     */
    public static Optional<TagReadResult> expected(Fixture fixture) {
        return Optional.ofNullable(switch (fixture) {
            case NO_TAGS -> result(List.of());
            case V1_0 -> result(List.of(layer(TagVersion.ID3V1_0, Map.of(
                    Field.TITLE, text("V1 Title"),
                    Field.ARTIST, text("V1 Artist"),
                    Field.ALBUM, text("V1 Album"),
                    Field.YEAR, new YearValue(1995),
                    Field.COMMENT, text("A comment of thirty bytes!!!!!"),
                    Field.GENRE, Genres.of("Pop")))));
            case V1_1 -> result(List.of(layer(TagVersion.ID3V1_1, Map.of(
                    Field.TITLE, text("V1.1 Title"),
                    Field.ARTIST, text("V1.1 Artist"),
                    Field.ALBUM, text("V1.1 Album"),
                    Field.YEAR, new YearValue(2003),
                    Field.COMMENT, text("Short"),
                    Field.TRACK, Position.of(7),
                    Field.GENRE, Genres.of("Rock")))));
            case V23_LATIN1 -> result(List.of(layer(TagVersion.ID3V2_3, Map.of(
                    Field.TITLE, text("Café Song"),
                    Field.ARTIST, text("Artist"),
                    Field.ALBUM_ARTIST, text("Album Artist"),
                    Field.ALBUM, text("Album"),
                    Field.TRACK, Position.of(3, 12),
                    Field.DISC, Position.of(1, 2),
                    Field.YEAR, new YearValue(2001),
                    Field.GENRE, Genres.of("Pop"),
                    Field.COMMENT, text("A comment")))));
            case V23_UTF16_CYRILLIC -> result(List.of(layer(TagVersion.ID3V2_3, Map.of(
                    Field.TITLE, text("Љубав 🎵"),
                    Field.ARTIST, text("Ђорђе Балашевић"),
                    Field.ALBUM, text("čćšžđ ČĆŠŽĐ"),
                    Field.YEAR, new YearValue(1986)))));
            case V24_UTF8 -> result(List.of(layer(TagVersion.ID3V2_4, Map.of(
                    Field.TITLE, text("Ünïcödé Title"),
                    Field.ARTIST, text("UTF-8 Artist"),
                    Field.YEAR, new YearValue(2020),
                    Field.GENRE, Genres.of("Pop", "Rock")))));
            case V22 -> result(List.of(layer(TagVersion.ID3V2_2, Map.of(
                    Field.TITLE, text("V22 Title"),
                    Field.ARTIST, text("V22 Artist"),
                    Field.ALBUM, text("V22 Album"),
                    Field.TRACK, Position.of(5, 10),
                    Field.YEAR, new YearValue(1999),
                    Field.GENRE, Genres.of("Pop")))));
            case V11_V23_SAME -> result(List.of(
                    layer(TagVersion.ID3V2_3, Map.of(
                            Field.TITLE, text("This Title Has Thirty One Chars"),
                            Field.ARTIST, text("Ђорђе Балашевић"),
                            Field.ALBUM, text("Album"),
                            Field.TRACK, Position.of(3, 12),
                            Field.YEAR, new YearValue(1986),
                            Field.GENRE, Genres.of("Rock"))),
                    layer(TagVersion.ID3V1_1, Map.of(
                            Field.TITLE, text("This Title Has Thirty One"),
                            Field.ARTIST, text("Djordje Balasevic"),
                            Field.ALBUM, text("Album"),
                            Field.TRACK, Position.of(3),
                            Field.YEAR, new YearValue(1986),
                            Field.GENRE, Genres.of("Rock")))));
            case V11_V23_DIFF -> result(List.of(
                    layer(TagVersion.ID3V2_3, Map.of(
                            Field.TITLE, text("Same Title"),
                            Field.ARTIST, text("Artist A"))),
                    layer(TagVersion.ID3V1_1, Map.of(
                            Field.TITLE, text("Same Title"),
                            Field.ARTIST, text("Artist B"),
                            Field.TRACK, Position.of(1)))));
            case V23_GENRE_REF -> result(List.of(layer(TagVersion.ID3V2_3, Map.of(
                    Field.TITLE, text("Genre Ref"),
                    Field.GENRE, Genres.of("Rock")))));
            case V23_GENRE_NUM -> result(List.of(layer(TagVersion.ID3V2_3, Map.of(
                    Field.TITLE, text("Genre Num"),
                    Field.GENRE, Genres.of("Rock")))));
            case V23_BAD_TRACK -> new TagReadResult(MediaFormat.MP3,
                    List.of(layer(TagVersion.ID3V2_3, Map.of(Field.TITLE, text("Bad Track")))),
                    Optional.of(STREAM), Optional.empty(),
                    List.of(Issue.warning(IssueCode.READ_VALUE_INVALID, "TRACK: A1").forField(Field.TRACK)));
            case V23_COVER -> withCover(layer(TagVersion.ID3V2_3, Map.of(Field.TITLE, text("With Cover"))),
                    PictureType.FRONT_COVER);
            case V23_OTHER_PICTURE -> withCover(
                    layer(TagVersion.ID3V2_3, Map.of(Field.TITLE, text("Other Picture"))), PictureType.OTHER);
            case CORRUPT, EMPTY -> null;
        });
    }

    /**
     * @param fixture a readable fixture
     * @return the expected result
     * @throws IllegalArgumentException if the fixture is not readable
     */
    public static TagReadResult require(Fixture fixture) {
        return expected(fixture).orElseThrow(() -> new IllegalArgumentException(fixture + " is not readable"));
    }

    /**
     * The raw value of a field in the fixture, i.e. what a reader must mention in a READ_VALUE_INVALID message.
     *
     * @param fixture a fixture
     * @return the raw invalid value, or empty if the fixture has none
     */
    public static Optional<String> invalidRawValue(Fixture fixture) {
        return fixture == Fixture.V23_BAD_TRACK ? Optional.of("A1") : Optional.empty();
    }

    private static TagReadResult result(List<TagLayer> layers) {
        return new TagReadResult(MediaFormat.MP3, layers, Optional.of(STREAM), Optional.empty(), List.of());
    }

    private static TagReadResult withCover(TagLayer layer, PictureType type) {
        return new TagReadResult(MediaFormat.MP3, List.of(layer), Optional.of(STREAM),
                Optional.of(new CoverInfo(type, "image/jpeg", COVER_JPEG_BYTES)), List.of());
    }

    private static TagLayer layer(TagVersion version, Map<Field, FieldValue> values) {
        return new TagLayer(version, new MediaMetadata(new EnumMap<>(values)));
    }

    private static Text text(String value) {
        return new Text(value);
    }
}
